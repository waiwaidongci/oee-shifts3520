import {request} from './client.js';
export const loadAll=async()=>Object.fromEntries(await Promise.all(['sources','periods','policies','runs','schedules','deliveries','audits','lines','lineruns'].map(async k=>[k,await request('/'+k)])));
export const saveSource=(data,id)=>request('/sources'+(id?'/'+id:''),id?'PUT':'POST',{data});
export const savePolicy=data=>request('/policies','POST',{data});
export const submitRun=data=>request('/runs','POST',data);
export const approveRun=(id,note)=>request('/runs/'+id+'/approve','POST',{note});
export const saveLinePlan=(data,id)=>request('/lines'+(id?'/'+id:''),id?'PUT':'POST',{data});
export const deleteLinePlan=id=>request('/lines/'+id,'DELETE');
export const resolveLine=id=>request('/lines/'+id+'/resolve');
export const submitLineRun=data=>request('/lineruns','POST',data);
